//#region Entity classes

type Shape = 'list' | 'listable' | 'single';

function platformClass(domain: string, spec: string): Promise<Made | ''> {
  const platform = spec.split('.')[1];
  return entityClass({
    name: pascal(platform) + pascal(domain),
    section: (root) => root[`${platform}.${domain}`]?.schemas?.CONFIG_SCHEMA,
    file: platform,
    actionNamespace: domain,
    kind: () => `{ domain: '${domain}', platform: '${platform}' }`,
    doc: `\`${domain}: - platform: ${platform}\``,
    factory: (name, opt) => factoryCall(name, opt, `${platform}_${domain}`),
  });
}

function componentClass(name: string): Promise<Made | ''> {
  return entityClass({
    name: pascal(name),
    section: (root) => root[name]?.schemas?.CONFIG_SCHEMA,
    file: name,
    block: true,
    actionNamespace: name,
    kind: (shape) => `{ domain: '${name}'${shape === 'list' ? '' : `, shape: '${shape}'`} }`,
    doc: `\`${name}:\``,
    factory: (cls, opt, shape) =>
      shape === 'single'
        ? `(props: ${cls}.Props${opt}): ${cls} => new ${cls}(currentScope(), '${name}', props)`
        : factoryCall(cls, opt, name),
  });
}

interface EntitySpec {
  name: string;
  section: (root: Json) => Json;
  file: string;
  /** Top-level blocks, not platform entries. */
  block?: boolean;
  /** Whose actions become methods, e.g. `fan` gives `fan.turn_on()`. */
  actionNamespace: string;
  kind: (shape: Shape) => string;
  doc: string;
  /** The expression for a function that builds the class in the current scope. */
  factory: (cls: string, optionalProps: string, shape: Shape) => string;
}

/** The overloaded builder for a class: with an optional id when it has no required props. */
const factoryCall = (cls: string, optionalProps: string, label: string): string =>
  optionalProps
    ? `optionalEntityFactory<${cls}.Props, ${cls}>(${cls}, '${label}')`
    : `entityFactory<${cls}.Props, ${cls}>(${cls}, '${label}')`;

const classNames = new Set<string>();

async function entityClass(spec: EntitySpec): Promise<Made | ''> {
  if (classNames.has(spec.name)) return '';
  classNames.add(spec.name);
  const config = spec.section(await load(spec.file));
  const found = await variantsOf(config);
  // components with no CONFIG_SCHEMA have no props to type
  if (!found) return '';
  const { key: typedKey, variants } = found;
  const shape: Shape =
    !spec.block || config.has_required_var ? 'list' : config.is_list ? 'listable' : 'single';
  const merged = Object.assign({}, ...variants.map((variant) => variant.vars)) as Record<
    string,
    Var
  >;
  const stepKeys = Object.entries(merged)
    .filter(([k, v]) => isSteps(k, v))
    .map(([k]) => k);
  const idVar = merged.id;
  const idMode =
    idVar?.key === 'Required'
      ? 'always'
      : /At least one of \*\*id\*\* and \*\*name\*\*/i.test(idVar?.docs ?? '')
        ? 'unlessNamed'
        : undefined;
  const triggerKeys = Object.entries(merged)
    .filter(([key, v]) => key !== 'id' && !v.id_type && isTrigger(key, v))
    .map(([key]) => key);
  const kind = withKindExtras(spec.kind(shape), [
    stepKeys.length ? `steps: [${stepKeys.map((k) => `'${k}'`).join(', ')}]` : '',
    triggerKeys.length ? `triggers: [${triggerKeys.map((k) => `'${k}'`).join(', ')}]` : '',
    idMode ? `id: '${idMode}'` : '',
  ]);
  const idTypes = variants.map((variant) => variant.vars.id?.id_type);
  const cpp = unique(idTypes.flatMap((t) => [t?.class, ...(t?.parents ?? [])])).filter(Boolean);
  const ownOf = (vars: Record<string, Var>) =>
    Object.entries(vars).filter(([key, v]) => key !== 'id' && !v.id_type);
  const own = ownOf(merged);
  const bodies = await Promise.all(
    variants.map(({ vars, schema }) =>
      schemaParts(schema, {
        // triggers are `on_x()` methods, and the id and switch key are declared on the props type
        omit: new Set([
          'id',
          ...(typedKey ? [typedKey] : []),
          ...Object.entries(vars)
            .filter(([key, v]) => isTrigger(key, v))
            .map(([key]) => key),
        ]),
        skip: (key, v) => key === 'id' || key === typedKey || isTrigger(key, v),
      }),
    ),
  );
  const triggerProps = await Promise.all(
    variants.map(({ vars }) => triggerPropLines(vars, spec.actionNamespace)),
  );
  const idProp =
    shape === 'single'
      ? ''
      : '  /** Its name in the tree, which the ESPHome id is built from; taken from `name` if omitted. */\n  id?: string;\n';
  // a `typed` schema picks one of several shapes by a key, which the default case may omit
  const optionalKey = /default/i.test(config.docs ?? '') ? '?' : '';
  const extend = ({ parents }: Parts): string =>
    parents.length ? ` extends ${parents.join(', ')}` : '';
  const members = typedKey
    ? variants
        .map(({ name }, i) => {
          return `interface ${variantName(name)}${extend(bodies[i])} {\n  ${propName(typedKey)}${optionalKey}: ${enumLiterals([String(name)])};\n${idProp}${bodies[i].own}${triggerProps[i]}}\n`;
        })
        .join('\n') +
      `\ntype Props =\n${variants.map(({ name }) => `  | ${variantName(name)}`).join('\n')};\n`
    : `interface Props${extend(bodies[0])} {\n${idProp}${bodies[0].own}${triggerProps[0]}}\n`;
  const required =
    variants.some(({ vars }) => hasRequired(ownOf(vars))) || (!!typedKey && !optionalKey);
  const triggers = own
    .filter(([key, v]) => isTrigger(key, v))
    .map(([key, v]) => triggerMethod(key, v, spec.actionNamespace))
    .join('');
  const methods = await entityMethods(spec.actionNamespace, cpp as string[]);
  const expr = spec.factory(spec.name, required ? '' : ' = {}', shape);
  const code = `
/** ${spec.doc} */
export class ${spec.name} extends Entity<${spec.name}.Props> {
  declare readonly cpp: Cpp<${cpp.map((c) => JSON.stringify(c)).join(' | ') || 'never'}>;

  constructor(scope: Construct, id: string, props: ${spec.name}.Props${required ? '' : ' = {}'}) {
    super(scope, id, ${kind}, props);
  }
${triggers}${methods}}

export declare namespace ${spec.name} {
${members}}
`;
  return { code, cls: spec.name, expr };
}

/** `Ds2482100` for variant `ds2482-100`, inside the class's namespace beside `Props`. */
const variantName = (variant: unknown): string => {
  const name = pascal(String(variant)).replace(/[^A-Za-z0-9_]/g, '') || 'Variant';
  return /^\d/.test(name) || name === 'Props' ? `Variant${name}` : name;
};

interface Variants {
  /** The key a `typed` schema switches on, e.g. `type`; absent for a plain schema. */
  key?: string;
  variants: { name?: string; vars: Record<string, Var>; schema: Schema }[];
}

async function variantsOf(config: Json): Promise<Variants | undefined> {
  if (config?.schema) {
    return { variants: [{ vars: await flatten(config.schema), schema: config.schema }] };
  }
  if (config?.type !== 'typed' || !config.types) return undefined;
  const variants = await Promise.all(
    Object.entries<Schema>(config.types).map(async ([name, schema]) => ({
      name,
      vars: await flatten(schema),
      schema,
    })),
  );
  return { key: config.typed_key, variants };
}

/** A prop holding steps: an action list, or a script's `then`. */
const isSteps = (key: string, v: Var): boolean =>
  v.registry === 'action' || (v.type === 'trigger' && key === 'then');

const withKindExtras = (kind: string, extras: string[]): string => {
  const present = extras.filter(Boolean);
  return present.length ? kind.replace(/ \}$/, `, ${present.join(', ')} }`) : kind;
};

/** `then` is a trigger in the schema, but a script's body is a prop rather than an `on_x()`. */
const isTrigger = (key: string, v: Var): boolean => v.type === 'trigger' && key !== 'then';

const hasRequired = (vars: [string, Var][]): boolean => vars.some(([, v]) => v.key === 'Required');

/** Methods for the actions and conditions that take this entity as their `id`: `sw.is_on()`. */
async function entityMethods(namespace: string, cpp: string[]): Promise<string> {
  const taken = new Set<string>();
  const tree: Tree = { members: [], children: new Map() };
  for (const section of ['action', 'condition'] as const) {
    const entries: [string, Json][] = Object.entries(
      (await load(namespace))[namespace]?.[section] ?? {},
    );
    const methods = await Promise.all(
      entries.map(([name, spec]) => entityMethod(namespace, section, name, spec, cpp)),
    );
    for (const method of methods.filter((m) => m !== undefined)) {
      const key = method.path.join('.');
      if (taken.has(key)) continue;
      taken.add(key);
      addToTree(
        tree,
        method.path.slice(0, -1),
        method.path.length > 1 ? method.arrow : method.method,
      );
    }
  }
  // a dotted action like `peer.add` is a getter returning an object: `espnow.peer.add(...)`
  return (
    tree.members.join('') +
    [...tree.children]
      .map(
        ([key, child]) =>
          `  get ${propName(key)}() {\n    return {\n${renderTree(child, (k) => `      ${k}: {\n`, '      },\n')}    };\n  }\n`,
      )
      .join('')
  );
}

interface EntityMethod {
  path: string[];
  /** As a class method, for a name with no dots. */
  method: string;
  /** As a property of the object a getter returns, for a dotted name. */
  arrow: string;
}

async function entityMethod(
  namespace: string,
  section: 'action' | 'condition',
  name: string,
  spec: Json,
  cpp: string[],
): Promise<EntityMethod | undefined> {
  const vars = await flatten(spec.schema ?? {});
  const doc = spec.docs ? `  /** ${docLine(spec.docs)} */\n` : '';
  const returns = section === 'action' ? 'Action' : 'Condition';
  // a platform's own builders are core even when the platform is external (`sensor.in_range`)
  const own = externalNamespaces.has(namespace);
  const kind = section === 'action' ? 'Actions' : 'Conditions';
  const builders = own ? `external${kind}` : kind.toLowerCase();
  const path = name.split('.');
  const leaf = path.at(-1)!;
  const fn = `${builders}.${propName(namespace)}.${path.join('.')}`;
  const make = (params: string, body: string): EntityMethod => ({
    path,
    method: `${doc}  ${leaf}(${params}): ${returns} {\n    return ${body};\n  }\n`,
    arrow: `${doc}      ${leaf}: (${params}): ${returns} => ${body},\n`,
  });
  if (takesId(vars)) {
    if (!cpp.includes(vars.id.use_id_type!)) return undefined;
    return make(`...rest: Tail<typeof ${fn}>`, `${fn}(this, ...rest)`);
  }
  // otherwise the entity fills whichever prop refers to it, e.g. `transmitter_id`
  const owner = Object.entries(vars).find(
    ([, v]) => v.type === 'use_id' && cpp.includes(v.use_id_type!),
  )?.[0];
  if (!owner) return undefined;
  const others = Object.entries(vars).filter(([k, v]) => k !== owner && !v.id_type);
  const props = `Omit<NonNullable<Parameters<typeof ${fn}>[0]>, '${owner}'>`;
  return make(
    `props: ${props}${hasRequired(others) ? '' : ' = {}'}`,
    `${fn}({ ...props, ${owner}: this })`,
  );
}

/** Whether a builder's first parameter is the entity, as `(id, props?)`. */
function takesId(vars: Record<string, Var>): boolean {
  const rest = Object.entries(vars).filter(([k, v]) => k !== 'id' && !v.id_type);
  // `(id?, props)` is invalid when props has a required field, so those take everything in props
  return vars.id?.type === 'use_id' && (vars.id.key === 'Required' || !hasRequired(rest));
}

