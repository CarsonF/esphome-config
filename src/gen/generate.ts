//#region Discovery

interface Catalog {
  /** `<domain>.<platform>`: entries of a `<domain>:` list. */
  platforms: string[];
  /** Top-level blocks, which have no platform. */
  components: string[];
  /** Whose actions and conditions get typed builders; `core` is delay, if, while, ... */
  namespaces: string[];
}

/** Everything the schema publishes: `core` lists domains and components, domains list platforms. */
async function discover(): Promise<Catalog> {
  const esphome = await load('esphome');
  const domains = Object.keys(esphome.core.platforms);
  const listed = await mapLimit(domains, async (domain) => {
    const platforms = Object.keys((await load(domain))[domain]?.components ?? {});
    return platforms.map((platform) => `${domain}.${platform}`);
  });
  // `esphome.ota` in esphome.json is the `esphome` platform of the `ota` domain
  const inCore = Object.keys(esphome)
    .filter((key) => key.includes('.'))
    .map((key) => key.split('.').reverse().join('.'));
  const components = Object.keys(esphome).filter((key) => key !== 'core' && !key.includes('.'));
  components.push(...Object.keys(esphome.core.components));
  return {
    platforms: unique([...listed.flat(), ...inCore]).sort(),
    components: unique(components).sort(),
    namespaces: unique(['core', ...domains, ...components]).sort(),
  };
}

/** Generates each, skipping the ones the schema doesn't describe well enough to type. */
async function generateAll(
  names: string[],
  make: (name: string) => Promise<Made | ''>,
): Promise<{ name: string; made: Made }[]> {
  const failed: string[] = [];
  const results = await mapLimit(names, async (name) => {
    try {
      const made = await make(name);
      if (made) generated++;
      else {
        skipped++;
        process.stderr.write(`skipped ${name}: no typed schema\n`);
      }
      return made ? { name, made } : undefined;
    } catch (error) {
      failed.push(`${name}: ${error}`);
      return undefined;
    }
  });
  // an error is a generator bug, not a schema gap, and would leave classes missing
  if (failed.length)
    throw new Error(
      `generation failed for ${failed.length}:\n  ${failed.slice(0, 10).join('\n  ')}`,
    );
  return results.filter((result) => result !== undefined);
}

/** A class with its props types, and the expression for its factory. */
interface Made {
  code: string;
  cls: string;
  expr: string;
}

async function mapLimit<T, R>(items: T[], fn: (item: T) => Promise<R>, limit = 16): Promise<R[]> {
  const results = new Array<R>(items.length);
  let next = 0;
  const worker = async (): Promise<void> => {
    while (next < items.length) {
      const index = next++;
      results[index] = await fn(items[index]);
    }
  };
  await Promise.all(Array.from({ length: limit }, worker));
  return results;
}

