//#region Schema loading

interface Var {
  key?: string;
  type?: string;
  docs?: string;
  values?: Record<string, unknown>;
  default?: unknown;
  is_list?: boolean;
  templatable?: boolean;
  /** A trigger whose options can't all be left out, so it needs `{ then, ...options }`. */
  has_required_var?: boolean;
  /** A pin that must be on the chip, not behind an expander. */
  internal?: boolean;
  /** The validator's name, which for a component's own validator says nothing about the value. */
  data_type?: string;
  registry?: string;
  use_id_type?: string;
  id_type?: { class: string; parents: string[] | null };
  schema?: Schema;
  /** `cv.maybe_simple_value`: the key a bare value is, e.g. `frames: int` for `{ type: int }`. */
  maybe?: string;
}

interface Schema {
  config_vars?: Record<string, Var>;
  extends?: string[];
}

// biome-ignore lint: the schema is untyped JSON
type Json = any;

/** Core files first; external components add their own beside them. */
async function load(file: string): Promise<Json> {
  const path = [SCHEMA, EXTERNAL]
    .filter((dir) => dir !== undefined)
    .map((dir) => `${dir}/${file}.json`)
    .find((candidate) => existsSync(candidate));
  return path ? JSON.parse(readFileSync(path, 'utf8')) : {};
}

/** `sensor._SENSOR_SCHEMA` lives in sensor.json, `core.X` in esphome.json. */
async function resolve(ref: string): Promise<Schema> {
  const dot = ref.lastIndexOf('.');
  const [namespace, name] = [ref.slice(0, dot), ref.slice(dot + 1)];
  const file = namespace === 'core' ? 'esphome' : namespace.split('.')[0];
  const root = await load(file);
  return root[namespace]?.schemas?.[name]?.schema ?? {};
}

/** Parents first, so a child that only overrides `default` keeps the parent's type. */
async function flatten(schema: Schema): Promise<Record<string, Var>> {
  const vars: Record<string, Var> = {};
  for (const ref of schema.extends ?? []) Object.assign(vars, await flatten(await resolve(ref)));
  for (const [key, own] of Object.entries(schema.config_vars ?? {})) {
    vars[key] = { ...vars[key], ...own };
  }
  return vars;
}

