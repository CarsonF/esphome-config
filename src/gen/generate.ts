/** One file per namespace, and an index that gathers them as `actions.fan.turn_on(...)`. */
async function writeActions(namespaces: string[]): Promise<void> {
  const found = (
    await mapLimit(namespaces, async (ns) => {
      const [actions, conditions] = [await builders(ns, 'action'), await builders(ns, 'condition')];
      if (!actions && !conditions) return undefined;
      const id = identifier(ns);
      write(
        `actions/${ns}`,
        `export const ${id}Actions = {\n${actions}};\n\nexport const ${id}Conditions = {\n${conditions}};\n`,
        1,
      );
      return { ns, id };
    })
  )
    .filter((entry) => entry !== undefined)
    .sort((a, b) => a.ns.localeCompare(b.ns));
  const member = (kind: 'Actions' | 'Conditions') =>
    found
      .map(({ ns, id }) =>
        ns === 'core' ? `  ...${id}${kind},` : `  ${propName(ns)}: ${id}${kind},`,
      )
      .join('\n');
  writeIndex(
    'actions',
    `${found.map(({ ns, id }) => `import { ${id}Actions, ${id}Conditions } from './${ns}.ts';`).join('\n')}

/** Typed \`then:\` steps, e.g. \`actions.fan.turn_on(cooler)\`. */
export const actions = {\n${member('Actions')}\n};

/** Typed conditions, e.g. \`conditions.not(conditions.sensor.in_range(temp, { above: 30 }))\`. */
export const conditions = {\n${member('Conditions')}\n};
`,
  );
}

/** A name safe to start a TypeScript identifier with. */
const identifier = (name: string): string => camel(name).replace(/^(\d)/, '_$1');

interface Tree {
  members: string[];
  children: Map<string, Tree>;
}

/** Dotted names nest: `display.set_rotation` is `display` holding `set_rotation`. */
function addToTree(tree: Tree, path: string[], member: string): void {
  if (path.length === 0) tree.members.push(member);
  else {
    const child = tree.children.get(path[0]) ?? { members: [], children: new Map() };
    tree.children.set(path[0], child);
    addToTree(child, path.slice(1), member);
  }
}

const renderTree = (tree: Tree, open: (key: string) => string, close: string): string =>
  tree.members.join('') +
  [...tree.children]
    .map(([key, child]) => `${open(propName(key))}${renderTree(child, open, close)}${close}`)
    .join('');

/** The members of one namespace's `actions` or `conditions` object; core ones are top-level. */
async function builders(component: string, section: 'action' | 'condition'): Promise<string> {
  const file = component === 'core' ? 'esphome' : component;
  const root = (await load(file))[component] ?? {};
  const entries: [string, Json][] = Object.entries(root[section] ?? {});
  const tree: Tree = { members: [], children: new Map() };
  await Promise.all(
    entries.map(async ([name, spec]) => {
      const path = name.split('.');
      const code = await builder(component, name, spec, path.at(-1)!).catch(() => '');
      if (code) addToTree(tree, path.slice(0, -1), code);
    }),
  );
  return renderTree(tree, (key) => `  ${key}: {\n`, '  },\n');
}

async function builder(component: string, name: string, spec: Json, leaf: string): Promise<string> {
  const key = component === 'core' ? name : `${component}.${name}`;
  const fn = propName(leaf);
  const doc = spec.docs ? `  /** ${docLine(spec.docs)} */\n` : '';
  const head = `${doc}  ${fn}`;
  const ret = `Config`;
  if (spec.type === 'registry' && spec.registry === 'condition') {
    return spec.is_list
      ? `${head}(...conditions: Many<Condition>[]): ${ret} {\n    return { '${key}': flat(conditions).map(toCondition) };\n  },\n`
      : `${head}(condition: Condition): ${ret} {\n    return { '${key}': toCondition(condition) };\n  },\n`;
  }
  if (spec.type && spec.type !== 'schema')
    return `${head}(value: unknown): ${ret} {\n    return { '${key}': value };\n  },\n`;
  const schema: Schema = spec.schema ?? {};
  const scalar =
    (schema.extends ?? []).some((ref) => /time_period/.test(ref)) && !schema.config_vars;
  if (!spec.schema)
    return `${head}(value: Lambda): ${ret} {\n    return { '${key}': value };\n  },\n`;
  if (scalar)
    return `${head}(value: Time | Lambda<number>): ${ret} {\n    return { '${key}': value };\n  },\n`;
  const vars = await flatten(schema);
  const rest = Object.entries(vars).filter(([k, v]) => k !== 'id' && !v.id_type);
  const propsType = typeOf(
    await schemaParts(schema, { omit: new Set(['id']), skip: (key) => key === 'id' }),
  );
  const steps = Object.entries(vars)
    .filter(([k, v]) => isSteps(k, v) || v.type === 'trigger')
    .map(([k]) => `'${k}'`);
  const conditionKeys = Object.entries(vars)
    .filter(([, v]) => v.registry === 'condition')
    .map(([k]) => `'${k}'`);
  const wrap = (p: string) =>
    steps.length || conditionKeys.length
      ? `withSteps(${p}, [${steps.join(', ')}], [${conditionKeys.join(', ')}])`
      : p;
  if (takesId(vars)) {
    const idVar = vars.id;
    const idType = `Ref<${JSON.stringify(idVar.use_id_type)}>`;
    const optionalId = idVar.key === 'Required' ? '' : '?';
    const propsOptional = hasRequired(rest) ? '' : '?';
    return `${head}(id${optionalId}: ${idType}, props${propsOptional}: ${propsType}): ${ret} {
    return { '${key}': props && Object.keys(props).length || ${spec.maybe !== 'id'} ? { id, ...${wrap('props')} } : (id ?? null) };
  },
`;
  }
  const propsOptional = hasRequired(Object.entries(vars)) ? '' : '?';
  const full = typeOf(await schemaParts(schema));
  return `${head}(props${propsOptional}: ${full}): ${ret} {
    return { '${key}': ${wrap('props')} ?? null };
  },
`;
}

