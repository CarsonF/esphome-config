/** Some list fields, like `api.actions`, are only marked as lists in their docs. */
/** About half the fields with no `type` upstream start their docs with one, e.g. `**float**:`. */
const docLabel = (docs: string | undefined): string | undefined =>
  docs
    ?.match(/^\*\*\[?([^\]*]+?)\]?(?:\([^)]*\))?\*\*/)?.[1]
    .toLowerCase()
    .trim();

function docType(docs: string | undefined): string | undefined {
  const label = docLabel(docs);
  if (!label) return undefined;
  const item = label.match(/^(?:a )?list of (.+?)s?$/)?.[1];
  if (item) return DOC_TYPES[item] ? `Array<${DOC_TYPES[item]}>` : 'Array<Any>';
  return DOC_TYPES[label];
}

/** Docs say `int` for fields that also take `100%` or `5s`, so strings are allowed too. */
const DOC_TYPES: Record<string, string> = {
  string: 'string | number | Tagged',
  icon: 'string',
  time: 'Time | Tagged',
  int: 'number | string | Tagged',
  float: 'number | string | Tagged',
  boolean: 'boolean | Tagged',
  lambda: 'string | Tagged',
  'mac address': 'string',
  percentage: 'Percent | number | Tagged',
  frequency: 'Frequency | number | Tagged',
  pin: 'Pin',
  'pin schema': 'Pin',
  integer: 'number | string | Tagged',
  'int or float': 'number | string | Tagged',
  uint32_t: 'number | string | Tagged',
  'float between 0 and 1': 'number | string | Tagged',
  bool: 'boolean | Tagged',
  mapping: 'Config',
  automation: 'Many<Step>',
  'ipv4 address': 'string',
  url: 'string',
  uuid: 'string',
  color: 'string',
  hex: 'string | number | Tagged',
  'byte array': 'Array<number>',
  list: 'Array<Any>',
};

/** ESPHome upper-cases these before matching, so `mode3` works for `MODE3`. */
function enumLiterals(keys: string[]): string {
  const letters = keys.filter((key) => /[A-Za-z]/.test(key));
  const upper = letters.length > 0 && letters.every((key) => key === key.toUpperCase());
  const all = upper ? unique([...keys, ...keys.map((key) => key.toLowerCase())]) : keys;
  return all.map((key) => JSON.stringify(key)).join(' | ');
}

/** `Time` and friends for a number the docs label with a unit; a plain `number` stays allowed. */
function unitType(v: Var): string | undefined {
  const type = DOC_TYPES[docLabel(v.docs) ?? ''];
  return type && ['time', 'frequency', 'percentage'].includes(docLabel(v.docs) ?? '')
    ? `number | ${type}`
    : undefined;
}

const takesUnits = (v: Var): boolean =>
  (typeof v.default === 'string' && !/^-?\d+(\.\d+)?$/.test(v.default)) ||
  ['time', 'frequency', 'percentage'].includes(docLabel(v.docs) ?? '');

const isList = (v: Var): boolean => !!v.is_list || (v.type === 'schema' && startsWithList(v));
const startsWithList = (v: Var): boolean => /^\*\*list\*\*/.test(v.docs ?? '');

/** A schema as the types it extends plus the props it adds, so each shared schema is typed once. */
interface Parts {
  parents: string[];
  own: string;
}

const typeOf = ({ parents, own }: Parts): string => [...parents, `{\n${own}}`].join(' & ');

/**
 * `extends` becomes a named type, which keeps recursive schemas finite (lvgl's widgets contain
 * widgets) and stops every platform repeating its base props.
 * `omit` hides inherited keys from every parent; `skip` drops own props.
 */
async function schemaParts(
  schema: Schema,
  {
    omit = new Set<string>(),
    skip,
  }: { omit?: Set<string>; skip?: (key: string, v: Var) => boolean } = {},
): Promise<Parts> {
  const refs = schema.extends ?? [];
  const parentVars = await Promise.all(refs.map(async (ref) => flatten(await resolve(ref))));
  const inherited = Object.assign({}, ...parentVars) as Record<string, Var>;
  const overridden = new Set<string>();
  const lines: string[] = [];
  for (const [key, own] of Object.entries(schema.config_vars ?? {})) {
    const merged = { ...inherited[key], ...own };
    if (merged.id_type || skip?.(key, merged)) continue;
    const before = inherited[key];
    // a child that only restates the parent's type, like a new default, inherits it
    if (before && (await signature(key, merged)) === (await signature(key, before))) continue;
    if (before) overridden.add(key);
    lines.push(await emitProp(key, merged));
  }
  const parents = refs.map((ref, i) => {
    // later parents win, as in flatten
    const hidden = new Set([...omit, ...overridden]);
    for (const later of parentVars.slice(i + 1))
      for (const key of Object.keys(later)) hidden.add(key);
    const name = sharedType(ref);
    return hidden.size
      ? `Omit<${name}, ${[...hidden].map((k) => JSON.stringify(k)).join(' | ')}>`
      : name;
  });
  return { parents, own: lines.join('') };
}

const signature = async (key: string, v: Var): Promise<string> =>
  `${v.key === 'Required' ? '' : '?'}:${await tsType(v, key)}`;

const sharedSchemas = new Map<string, Promise<string>>();

/** `S.sensor___SENSOR_SCHEMA` for ref `sensor._SENSOR_SCHEMA`, declared once in schemas.ts. */
function sharedType(ref: string): string {
  const name = ref.replace(/\./g, '_');
  if (!sharedSchemas.has(ref)) {
    sharedSchemas.set(
      ref,
      resolve(ref)
        .then(schemaParts)
        .then((parts) => `export type ${name} = ${typeOf(parts)};\n`),
    );
  }
  return `S.${name}`;
}

/** schemas.ts holds every shared schema the generated code referred to, and the ones those use. */
async function writeShared(): Promise<void> {
  const bodies: string[] = [];
  const written = new Set<string>();
  while (written.size < sharedSchemas.size) {
    for (const [ref, body] of [...sharedSchemas]) {
      if (written.has(ref)) continue;
      written.add(ref);
      bodies.push(await body);
    }
  }
  write('schemas', bodies.sort().join('\n'));
}

async function emitProp(key: string, v: Var): Promise<string> {
  const optional = v.key === 'Required' ? '' : '?';
  const doc = v.docs ? `  /** ${docLine(v.docs)} */\n` : '';
  return `${doc}  ${propName(key)}${optional}: ${await tsType(v, key)};\n`;
}

/** Fields named like `carrier_frequency` or `update_interval` take that unit, schema aside. */
const NAME_TYPES: [RegExp, string][] = [
  [/(^|_)frequency$/, 'Frequency | number | Tagged'],
  [/(^|_)(interval|timeout|duration|delay|period|time)$/, 'Time | Tagged'],
];

/** Anywhere a `!lambda` goes, a `cpp()` function goes too. */
async function tsType(v: Var, name?: string): Promise<string> {
  return (await rawType(v, name)).replace(/\bTagged\b/g, 'Lambda');
}

/** What a computed value has to return, when the schema says what the field is. */
const lambdaReturn = (v: Var): string =>
  v.type === 'boolean'
    ? 'boolean'
    : v.type === 'integer' || v.type === 'float'
      ? 'number'
      : v.type === 'string'
        ? 'string'
        : 'unknown';

async function rawType(v: Var, name?: string): Promise<string> {
  const byName = NAME_TYPES.find(([pattern]) => name && pattern.test(name));
  if (byName && !isList(v) && [undefined, 'integer', 'float', 'string'].includes(v.type))
    return byName[1];
  const base = await baseType(v);
  const inferredList = v.type === undefined && base.startsWith('Array<');
  const type = isList(v) && v.registry !== 'action' && !inferredList ? `Array<${base}>` : base;
  // a templatable field also takes a `!lambda`
  return v.templatable && v.type !== undefined && !isList(v)
    ? `${type} | Lambda<${lambdaReturn(v)}>`
    : type;
}

/** A validator ESPHome doesn't ship, like `cv.Any(cv.percentage, distance)`, may take more. */
const customValidator = (v: Var): boolean =>
  !!v.data_type && !/^(u?int(8|16|32|64)_t|float|double)$/.test(v.data_type);

async function nestedSchema(v: Var): Promise<string> {
  const type = await schemaType(v);
  const simple = v.maybe && v.schema ? (await flatten(v.schema))[v.maybe] : undefined;
  const bare = simple && (await tsType(simple, v.maybe));
  // an untyped key would make the whole field untyped
  return bare && bare !== 'Any' && bare !== 'unknown' ? `${type} | ${bare}` : type;
}

async function schemaType(v: Var): Promise<string> {
  if (!v.schema) return 'Config';
  // a bare `cv.time_period` is `120ms`, not an object with no keys
  if ((v.schema.extends ?? []).some((ref) => /time_period/.test(ref)) && !v.schema.config_vars) {
    return 'Time | Lambda<number>';
  }
  const entries = Object.entries(await flatten(v.schema)).filter(([, n]) => !n.id_type);
  // a dict with any keys, like `variables:`, is described by a single placeholder var `string`
  if (entries.length === 1 && entries[0][0] === 'string') {
    return `Record<string, ${await tsType(entries[0][1])}>`;
  }
  return typeOf(await schemaParts(v.schema));
}

async function baseType(v: Var): Promise<string> {
  switch (v.type) {
    case 'boolean':
      return 'boolean';
    case 'integer':
    case 'float':
      // some take units too, like `carrier_frequency: 38kHz` or `deviation: 5kHz`
      return unitType(v) ?? (takesUnits(v) || customValidator(v) ? 'number | string' : 'number');
    case 'string':
      return 'string';
    case 'enum':
      // `cv.Any('auto', {...})` is both: the literals, or the schema
      return [
        enumLiterals(Object.keys(v.values ?? {})) || 'string',
        ...(v.schema ? [await nestedSchema(v)] : []),
      ].join(' | ');
    case 'pin':
      return v.internal ? 'InternalPin' : 'Pin';
    case 'use_id':
      // no entity is of a class without a namespace, like `Device`, so it is the id as written
      return v.use_id_type?.includes('::') ? `Ref<${JSON.stringify(v.use_id_type)}>` : 'string';
    case 'trigger':
      return 'Many<Step>';
    case 'registry':
      return v.registry === 'action'
        ? 'Many<Step>'
        : v.registry === 'condition'
          ? 'Condition'
          : // a filter with no options is just its name, like `- invert`
            'Config | string';
    case 'schema':
      return nestedSchema(v);
    case undefined:
      return docType(v.docs) ?? 'Any';
    default:
      return 'unknown';
  }
}

