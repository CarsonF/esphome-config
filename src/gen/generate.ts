import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import process from 'node:process';
import { unique } from 'remeda';
import { membersSource } from './cpp-members.ts';

/**
 * Writes `out` from ESPHome's language schema: a class and its types for every component and
 * platform, typed `actions` and `conditions`, and the registry `esp` is typed from.
 * With `external`, only the components dumped there, as an augmentation of the package's registry.
 * Example: await generate({ version: '2026.9.1', schema: '/path/to/schema', out: 'src/generated' })
 */
export async function generate(options: GenerateOptions): Promise<void> {
  ({ version: VERSION, schema: SCHEMA, out: OUT, external: EXTERNAL } = options);
  SOURCES = options.sources ?? [];
  EXTERNAL_MODE = EXTERNAL !== undefined;
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  const catalog = EXTERNAL_MODE ? discoverExternal() : await discover();
  if (EXTERNAL_MODE) externalNamespaces = new Set(catalog.namespaces);
  else {
    writeReserved(catalog);
    writeVersion();
    writeFileSync(`${OUT}/members.ts`, membersSource('// Generated by esphome-config; do not edit.'));
  }
  await generateTypes(catalog);
}

export interface GenerateOptions {
  /** The ESPHome version the schema is for. */
  version: string;
  /** A directory with the esphome-schema release's JSON files. */
  schema: string;
  out: string;
  /** A directory with the external components' schema dump, one `<component>.json` each. */
  external?: string;
  /** External mode: the sources the components come from, each an `esp.external.<name>()`. */
  sources?: ExternalSource[];
}

/** Example: { name: 'roode', source: 'github://Lyr3x/Roode@b975cec', components: ['roode'] } */
export interface ExternalSource {
  name: string;
  /** As `external_components` takes it: `github://...`, or `{ type: 'local', path }`. */
  source: string | { type: 'local'; path: string };
  components: string[];
}

/** What the external dump holds: `<name>.json` has `<name>` and `<name>.<domain>` entries. */
function discoverExternal(): Catalog {
  const dir = EXTERNAL!;
  const platforms: string[] = [];
  const components: string[] = [];
  for (const file of readdirSync(dir).filter((name) => name.endsWith('.json'))) {
    const name = file.slice(0, -'.json'.length);
    for (const key of Object.keys(JSON.parse(readFileSync(`${dir}/${file}`, 'utf8')))) {
      if (key === name) components.push(name);
      else if (key.startsWith(`${name}.`)) platforms.push(`${key.split('.')[1]}.${name}`);
    }
  }
  const named = [...components, ...platforms.map((spec) => spec.split('.')[1])];
  return {
    platforms: platforms.sort(),
    components: components.sort(),
    namespaces: unique(named).sort(),
  };
}

async function generateTypes(catalog: Catalog): Promise<void> {
  const modules = EXTERNAL_MODE ? ['sources.ts'] : ['reserved.ts', 'version.ts'];
  if (EXTERNAL_MODE) writeSources();
  const keywords: string[] = [];
  const domainNames: string[] = [];
  for (const [domain, specs] of Map.groupBy(catalog.platforms, (spec) => spec.split('.')[0])) {
    const made = await generateAll(specs, (spec) => platformClass(domain, spec));
    for (const { name: spec, made: m } of made) {
      write(
        `${domain}/${spec.split('.')[1]}`,
        `${m.code}\nexport const make${m.cls} = ${m.expr};\n`,
        1,
      );
    }
    const entries = made.map(
      ({ name: spec, made: m }) => `  ${propName(spec.split('.')[1])}: make${m.cls},`,
    );
    writeIndex(
      domain,
      [
        ...made.map(
          ({ name: spec, made: m }) => `import { make${m.cls} } from './${spec.split('.')[1]}.ts';`,
        ),
        ...made.map(({ name: spec }) => `export * from './${spec.split('.')[1]}.ts';`),
        `export const ${safe(domain)} = {\n${entries.sort().join('\n')}\n};`,
      ].join('\n') + '\n',
    );
    modules.push(`${domain}/index.ts`);
    domainNames.push(domain);
    if (safe(domain) !== domain)
      keywords.push(`export { ${safe(domain)} as ${domain} } from './${domain}/index.ts';\n`);
  }
  const domains = new Set(catalog.platforms.map((spec) => spec.split('.')[0]));
  const components = catalog.components.filter((name) => !domains.has(name) && name !== 'globals');
  const made = await generateAll(components, componentClass);
  for (const { name, made: m } of made) {
    write(`components/${name}`, `${m.code}\nexport const ${safe(name)} = ${m.expr};\n`, 1);
    if (safe(name) !== name)
      keywords.push(`export { ${safe(name)} as ${name} } from './components/index.ts';\n`);
  }
  writeIndex('components', made.map(({ name }) => `export * from './${name}.ts';\n`).join(''));
  await writeActions(catalog.namespaces);
  writeRegistry(
    domainNames,
    made.map(({ name }) => name),
  );
  await writeShared();
  modules.push('components/index.ts', 'actions/index.ts');
  const lines = [...modules.map((m) => `export * from './${m}';\n`), ...keywords];
  writeFileSync(`${OUT}/index.ts`, lines.join(''));
  process.stdout.write(
    `generated ${generated} classes for ESPHome ${VERSION}, skipped ${skipped}\n`,
  );
}

//#region Registry

/**
 * The interfaces `esp` is typed from, which external components extend by declaration merging.
 * Example: `interface SensorPlatforms` has `adc`, and an external adds `roode`
 */
function writeRegistry(domains: string[], components: string[]): void {
  const header = `// Generated by esphome-config from the ESPHome ${VERSION} schema; do not edit.\n`;
  const imports = [
    ...domains.map((d) => `import type * as D_${d} from './${d}/index.ts';`),
    `import type * as C from './components/index.ts';`,
    `import type * as A from './actions/index.ts';`,
    ...(EXTERNAL_MODE ? [`import type * as X from './sources.ts';`] : []),
  ].join('\n');
  // an interface can extend an alias, but not a `typeof` query
  const aliases = [
    ...domains.map((d) => `type Own_${d} = typeof D_${d}.${safe(d)};`),
    'type OwnActions = typeof A.actions;',
    'type OwnConditions = typeof A.conditions;',
  ].join('\n');
  const declarations = `export interface Domains {
${domains.map((d) => `  ${propName(d)}: ${pascal(d)}Platforms;`).join('\n')}
}
${domains.map((d) => `export interface ${pascal(d)}Platforms extends Own_${d} {}`).join('\n')}
export interface Components {
${components.map((c) => `  ${propName(c)}: typeof C.${safe(c)};`).join('\n')}
}
export interface Actions extends OwnActions {}
export interface Conditions extends OwnConditions {}
export interface ExternalSources {
${SOURCES.map(({ name }) => `  ${name}: typeof X.external.${name};`).join('\n')}
}`;
  if (!EXTERNAL_MODE) {
    writeFileSync(`${OUT}/registry.ts`, `${header}${imports}\n\n${aliases}\n\n${declarations}\n`);
    return;
  }
  writeFileSync(
    `${OUT}/register.ts`,
    `${header}import { registerExternal } from 'esphome-config';
import * as external from './index.ts';
${imports}

registerExternal(external);

${aliases}

declare module 'esphome-config/registry' {
${indent(declarations.replace(/^export /gm, ''))}
}
`,
  );
}

/** `esp.external.<name>()`: each source's `external_components` entry, with its components. */
function writeSources(): void {
  const entries = SOURCES.map(
    ({ name, source, components }) =>
      `  ${name}: externalSource(${JSON.stringify(source)}, ${JSON.stringify(components.toSorted())}),`,
  );
  writeFileSync(
    `${OUT}/sources.ts`,
    `// Generated by esphome-config; do not edit.
import { externalSource } from 'esphome-config';

export const external = {
${entries.join('\n')}
};
`,
  );
}

const indent = (text: string): string =>
  text
    .split('\n')
    .map((line) => (line ? `  ${line}` : line))
    .join('\n');

//#endregion

/** Ids ESPHome rejects because they name an integration; entities get a `_` suffix instead. */
function writeReserved(catalog: Catalog): void {
  const names = new Set([...catalog.components, ...catalog.namespaces]);
  catalog.platforms.forEach((spec) => names.add(spec.split('.')[1]));
  writeFileSync(
    `${OUT}/reserved.ts`,
    `// Generated by esphome-config from the ESPHome ${VERSION} schema; do not edit.
import { reserveIds } from '../dsl/index.ts';

reserveIds('${[...names].sort().join(' ')}'.split(' '));
`,
  );
}

/** The ESPHome version the types are for, exported by the package. */
function writeVersion(): void {
  writeFileSync(
    `${OUT}/version.ts`,
    `// Generated by esphome-config; do not edit.
export const ESPHOME_VERSION = '${VERSION}';
`,
  );
}

