/** First paragraph with links flattened, and any comment terminator defused. */
function docLine(docs: string): string {
  return docs
    .split('\n\n')[0]
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/\*\//g, '* /')
    .replace(/\s+/g, ' ')
    .trim();
}

